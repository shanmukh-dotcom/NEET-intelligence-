def generate_synthetic_population(config: dict) -> pd.DataFrame:
    """
    Generate a synthetic youth population with longitudinal histories.

    Parameters
    ----------
    config : dict
        Configuration with keys:
        - n_individuals (int): Number of people (100–100,000)
        - n_waves (int): Number of survey waves (1–6)
        - waves (list[int]): Specific wave years (default 2021-2026)
        - female_pct (float): Proportion female (0–1)
        - rural_pct (float): Proportion rural (0–1)
        - education_dist (dict): Distribution over education levels
        - income_dist (list[float]): Probabilities for quintiles 1-5
        - neet_prevalence_target (float): Target NEET prevalence (0–1)
        - attrition_rate (float): Per-wave attrition probability
        - missing_rate (float): Per-observation missing probability
        - migration_rate (float): Proportion migrants
        - disability_rate (float): Proportion with disability
        - seed (int): Random seed
        - married_pct (float): Proportion married

    Returns
    -------
    pd.DataFrame
        Long-format dataset with one row per person-wave.
    """
    n = config.get("n_individuals", 5000)
    n = max(10, min(100000, n))
    n_waves = config.get("n_waves", 6)
    n_waves = max(1, min(6, n_waves))
    waves = config.get("waves", WAVES[:n_waves])
    seed = config.get("seed", 42)
    rng = np.random.RandomState(seed)

    female_pct = config.get("female_pct", 0.50)
    rural_pct = config.get("rural_pct", 0.55)
    attrition_rate = config.get("attrition_rate", 0.08)
    missing_rate = config.get("missing_rate", 0.05)
    migration_rate = config.get("migration_rate", 0.12)
    disability_rate = config.get("disability_rate", 0.05)
    married_pct = config.get("married_pct", 0.30)

    education_dist = config.get("education_dist", {
        "No formal education": 0.08,
        "Primary (1-5)": 0.12,
        "Upper primary (6-8)": 0.15,
        "Secondary (9-10)": 0.25,
        "Higher secondary (11-12)": 0.20,
        "Graduate": 0.15,
        "Postgraduate": 0.05,
    })

    income_dist = config.get("income_dist", [0.20, 0.20, 0.20, 0.20, 0.20])

    # Age distribution
    age_min = config.get("age_min", 15)
    age_max = config.get("age_max", 35)

    all_records = []

    for i in range(n):
        pid = f"SYN-{i:05d}"
        gender = "Female" if rng.random() < female_pct else "Male"
        rural_urban = "Rural" if rng.random() < rural_pct else "Urban"
        age = int(rng.randint(age_min, age_max + 1))
        edu_keys = list(education_dist.keys())
        edu_probs = np.array([education_dist[k] for k in edu_keys], dtype=float)
        edu_probs /= edu_probs.sum()
        education_level = rng.choice(edu_keys, p=edu_probs)

        # Constrain education by age
        if age <= 17 and education_level in ["Graduate", "Postgraduate"]:
            education_level = "Secondary (9-10)"
        elif age <= 19 and education_level == "Postgraduate":
            education_level = "Higher secondary (11-12)"

        income_quintile = int(rng.choice([1, 2, 3, 4, 5], p=income_dist))
        marital_status = "Married" if rng.random() < married_pct else "Never married"
        if age < 18:
            marital_status = "Never married"

        if rng.random() < migration_rate:
            migration_status = rng.choice(["Internal migrant", "Seasonal migrant",
                                           "Return migrant"])
        else:
            migration_status = "Non-migrant"

        disability_status = "Has disability" if rng.random() < disability_rate else "No disability"
        locality = rng.choice(FICTIONAL_LOCALITIES)

        person_cfg = {
            "person_id": pid,
            "gender": gender,
            "rural_urban": rural_urban,
            "age": age,
            "education_level": education_level,
            "marital_status": marital_status,
            "income_quintile": income_quintile,
            "migration_status": migration_status,
            "disability_status": disability_status,
            "locality": locality,
            "attrition_rate": attrition_rate,
            "missing_rate": missing_rate,
            "waves": waves,
        }

        history = generate_individual_history(person_cfg, n_waves, rng)
        all_records.extend(history)

    df = pd.DataFrame(all_records)

    # Add dataset-level metadata columns
    df["dataset_id"] = config.get("dataset_id", f"SYNTH-{seed}")
    df["generated_at"] = datetime.utcnow().isoformat()

    return df


