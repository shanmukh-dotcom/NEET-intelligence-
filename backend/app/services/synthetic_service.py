# Individual History Generator
# ---------------------------------------------------------------------------

def generate_individual_history(person_config: dict, num_waves: int,
                                rng: np.random.RandomState = None) -> list[dict]:
    """
    Generate longitudinal activity records for a single individual.

    Parameters
    ----------
    person_config : dict
        Demographic attributes for the individual.
    num_waves : int
        Number of survey waves to generate.
    rng : np.random.RandomState, optional
        Random state for reproducibility.

    Returns
    -------
    list[dict]
        One record per wave with activity state and supplementary indicators.
    """
    if rng is None:
        rng = np.random.RandomState(42)

    trans = _transition_probs_for_individual(person_config)
    person_id = person_config.get("person_id", f"SYN-{rng.randint(10000, 99999):05d}")
    gender = person_config.get("gender", "Male")
    age_start = person_config.get("age", 20)
    attrition_rate = person_config.get("attrition_rate", 0.08)
    missing_rate = person_config.get("missing_rate", 0.05)
    waves = person_config.get("waves", WAVES[:num_waves])

    # Determine initial state
    initial_state = person_config.get("initial_state", None)
    if initial_state is None:
        if age_start <= 18:
            initial_probs = [0.60, 0.10, 0.05, 0.25]
        elif age_start <= 24:
            initial_probs = [0.25, 0.35, 0.10, 0.30]
        else:
            initial_probs = [0.08, 0.55, 0.07, 0.30]
        # Gender adjustment for initial state
        if gender == "Female":
            initial_probs[3] += 0.08  # higher NEET
            initial_probs[1] -= 0.08  # lower employment
            initial_probs = [max(p, 0.01) for p in initial_probs]
            s = sum(initial_probs)
            initial_probs = [p / s for p in initial_probs]
        initial_state = rng.choice(ACTIVITY_STATES, p=initial_probs)

    current_state = initial_state
    records = []
    attrited = False

    for i, wave in enumerate(waves):
        if attrited:
            break

        # Missing data
        is_missing = rng.random() < missing_rate
        if is_missing and i > 0:
            records.append({
                "person_id": person_id,
                "wave": wave,
                "age": age_start + i,
                "activity_state": np.nan,
                "is_missing": True,
                "is_synthetic": True,
            })
            # Attrition check
            if rng.random() < attrition_rate:
                attrited = True
            continue

        # Transition (except wave 0)
        if i > 0:
            probs = trans[current_state]
            prob_vec = [probs[s] for s in ACTIVITY_STATES]
            current_state = rng.choice(ACTIVITY_STATES, p=prob_vec)

        # Generate supplementary indicators
        work_hours = 0.0
        unpaid_care_hours = 0.0
        is_informal = False
        is_underemployed = False

        if current_state == "Employment":
            work_hours = float(rng.normal(42, 12))
            work_hours = max(1, min(80, work_hours))
            is_informal = rng.random() < (0.75 if person_config.get("rural_urban") == "Rural" else 0.45)
            is_underemployed = work_hours < 20 or rng.random() < 0.15
        elif current_state == "Training":
            work_hours = float(rng.normal(10, 5))
            work_hours = max(0, min(30, work_hours))
        elif current_state == "Education":
            work_hours = 0.0
        else:  # NEET
            work_hours = 0.0

        # Unpaid care hours
        if gender == "Female":
            unpaid_care_hours = float(rng.exponential(4.5))
            unpaid_care_hours = min(16, unpaid_care_hours)
            if person_config.get("marital_status") == "Married":
                unpaid_care_hours += rng.exponential(2.0)
                unpaid_care_hours = min(16, unpaid_care_hours)
        else:
            unpaid_care_hours = float(rng.exponential(1.2))
            unpaid_care_hours = min(8, unpaid_care_hours)

        # Migration status may change
        migration = person_config.get("migration_status", "Non-migrant")
        if migration == "Seasonal migrant" and rng.random() < 0.3:
            migration = "Non-migrant" if rng.random() < 0.5 else "Seasonal migrant"

        record = {
            "person_id": person_id,
            "wave": wave,
            "age": age_start + i,
            "gender": gender,
            "rural_urban": person_config.get("rural_urban", "Urban"),
            "education_level": person_config.get("education_level", "Secondary (9-10)"),
            "marital_status": person_config.get("marital_status", "Never married"),
            "income_quintile": person_config.get("income_quintile", 3),
            "migration_status": migration,
            "disability_status": person_config.get("disability_status", "No disability"),
            "locality": person_config.get("locality", "Fictional District A1"),
            "activity_state": current_state,
            "work_hours": round(work_hours, 1),
            "unpaid_care_hours": round(unpaid_care_hours, 1),
            "is_informal": is_informal if current_state == "Employment" else False,
            "is_underemployed": is_underemployed if current_state == "Employment" else False,
            "is_missing": False,
            "is_synthetic": True,
        }
        records.append(record)

        # Attrition check at end of wave
        if rng.random() < attrition_rate and i < len(waves) - 1:
            attrited = True

    return records


