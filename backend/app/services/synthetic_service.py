"""
Synthetic Data Generation Engine for NEET Intelligence Platform.

Generates configurable synthetic youth populations with realistic
longitudinal activity histories using transition probability matrices.

ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC.
It must never be presented as real Indian statistics.
"""

